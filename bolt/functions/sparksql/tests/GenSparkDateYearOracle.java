import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.List;
import java.util.TimeZone;
import org.apache.spark.sql.catalyst.util.DateFormatter;
import org.apache.spark.sql.catalyst.util.DateFormatter$;
import org.apache.spark.sql.internal.SQLConf;

/**
 * Generate year-formatting cases using Spark's actual DATE formatter.
 * Compile with Spark 3.2 jars on the classpath. On Java 17, run with
 * --add-exports=java.base/sun.util.calendar=ALL-UNNAMED.
 * Usage: GenSparkDateYearOracle --output|--check SparkDateYearOracle.inc
 */
public final class GenSparkDateYearOracle {
  public static void main(String[] args) throws Exception {
    if (args.length != 2 || !(args[0].equals("--output") || args[0].equals("--check"))) {
      throw new IllegalArgumentException("Expected --output|--check <file>");
    }
    TimeZone.setDefault(TimeZone.getTimeZone("UTC"));
    int[] years = {-10001, -10000, -9999, -1000, -999, -100, -99, -10, -9, -1,
        0, 1, 9, 10, 99, 100, 526, 999, 1000, 9999, 10000, 10001};
    List<LocalDate> dates = new ArrayList<>();
    for (int year : years) {
      dates.add(LocalDate.of(year, 1, 1));
    }
    dates.add(LocalDate.of(2037, 12, 31).plusDays(-1222377472L));
    StringBuilder out = new StringBuilder(
        "/*\n"
        + " * Copyright (c) ByteDance Ltd. and/or its affiliates.\n"
        + " *\n"
        + " * Licensed under the Apache License, Version 2.0 (the \"License\");\n"
        + " * you may not use this file except in compliance with the License.\n"
        + " * You may obtain a copy of the License at\n"
        + " *\n"
        + " *     http://www.apache.org/licenses/LICENSE-2.0\n"
        + " *\n"
        + " * Unless required by applicable law or agreed to in writing, software\n"
        + " * distributed under the License is distributed on an \"AS IS\" BASIS,\n"
        + " * WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.\n"
        + " * See the License for the specific language governing permissions and\n"
        + " * limitations under the License.\n"
        + " */\n"
        + "\n"
        + "// Generated by GenSparkDateYearOracle.java using Spark DateFormatter in UTC.\n"
        + "// Year boundaries and a large negative DATE_ADD regression.\n"
        + "static const SparkDateYearCase kSparkDateYearCases[] = {\n");
    for (String policy : new String[]{"LEGACY", "CORRECTED", "EXCEPTION"}) {
      SQLConf.get().setConfString("spark.sql.legacy.timeParserPolicy", policy);
      DateFormatter formatter = DateFormatter$.MODULE$.apply();
      for (LocalDate date : dates) {
        int day = Math.toIntExact(date.toEpochDay());
        out.append("    {\"").append(policy).append("\", ").append(day)
            .append(", \"").append(formatter.format(day)).append("\"},\n");
      }
    }
    out.append("};\n");
    Path path = Paths.get(args[1]);
    byte[] bytes = out.toString().getBytes(StandardCharsets.UTF_8);
    if (args[0].equals("--output")) {
      Files.write(path, bytes);
    } else if (!java.util.Arrays.equals(Files.readAllBytes(path), bytes)) {
      throw new IllegalStateException("Spark year-formatting oracle differs: " + path);
    }
  }
}
